// Generates app/graphql/resolvers/types.d.ts from the .gql schema files, so resolvers can annotate
// their arguments with JSDoc and get intellisense/documentation for them in the editor.
//
// Run with `npm run schema:types` after changing the schema.
import { makeExecutableSchema } from '@graphql-tools/schema'
import {
  getNamedType,
  GraphQLEnumType,
  GraphQLInputObjectType,
  GraphQLList,
  GraphQLNonNull,
  GraphQLObjectType,
  GraphQLScalarType
} from 'graphql'
import { IBANTypeDefinition } from 'graphql-scalars'
import { execFileSync } from 'node:child_process'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const typesDir = join(root, 'app/graphql/types')
const outFile = join(root, 'app/graphql/resolvers/types.d.ts')

// Scalars are passed to resolvers as they arrive in the request, so custom scalars without a
// parseValue (Date, UUID etc.) are strings
const SCALARS = {
  ID: 'string',
  String: 'string',
  Int: 'number',
  Float: 'number',
  Numeric: 'number',
  Boolean: 'boolean'
}

const files = (await readdir(typesDir, { recursive: true }))
  .filter((file) => file.endsWith('.gql'))
  .sort((a, b) => a.localeCompare(b))
const typeDefs = await Promise.all(files.map((file) => readFile(join(typesDir, file), 'utf8')))
const schema = makeExecutableSchema({ typeDefs: [...typeDefs, IBANTypeDefinition] })

const pascal = (name) => name.charAt(0).toUpperCase() + name.slice(1)

const docComment = (lines, indent = '') => {
  const text = lines.filter(Boolean).join('\n\n').trim()
  if (!text) {
    return ''
  }
  const body = text
    .split('\n')
    .map((line) => `${indent} *${line ? ` ${line.replaceAll('*/', '*\\/')}` : ''}`)
    .join('\n')
  return `${indent}/**\n${body}\n${indent} */\n`
}

const describeField = (field) => [
  field.description,
  field.defaultValue !== undefined && `@default ${JSON.stringify(field.defaultValue)}`,
  field.deprecationReason && `@deprecated ${field.deprecationReason}`
]

const tsType = (type) => {
  if (type instanceof GraphQLNonNull) {
    return tsType(type.ofType).replace(/ \| null$/, '')
  }
  if (type instanceof GraphQLList) {
    return `Array<${tsType(type.ofType)}> | null`
  }
  if (type instanceof GraphQLScalarType) {
    return `${SCALARS[type.name] ?? 'string'} | null`
  }
  return `${type.name} | null`
}

const fieldsBlock = (fields) =>
  fields
    .map((field) => {
      const optional = !(field.type instanceof GraphQLNonNull)
      return `${docComment(describeField(field), '  ')}  ${field.name}${optional ? '?' : ''}: ${tsType(field.type)}`
    })
    .join('\n')

// Only emit types reachable from field arguments, i.e. those a resolver can actually receive
const used = new Set()
const collect = (type) => {
  const named = getNamedType(type)
  if (used.has(named.name)) {
    return
  }
  used.add(named.name)
  if (named instanceof GraphQLInputObjectType) {
    Object.values(named.getFields()).forEach((field) => collect(field.type))
  }
}

const objectTypes = Object.values(schema.getTypeMap())
  .filter((type) => type instanceof GraphQLObjectType && !type.name.startsWith('__'))
  .sort((a, b) => a.name.localeCompare(b.name))

const argsTypes = []
for (const type of objectTypes) {
  for (const field of Object.values(type.getFields())) {
    if (!field.args.length) {
      continue
    }
    field.args.forEach((arg) => collect(arg.type))
    argsTypes.push(
      `${docComment([`Arguments for \`${type.name}.${field.name}\``, field.description])}` +
        `export interface ${type.name}${pascal(field.name)}Args {\n${fieldsBlock(field.args)}\n}`
    )
  }
}

const namedTypes = [...used]
  .sort((a, b) => a.localeCompare(b))
  .map((name) => schema.getType(name))
  .flatMap((type) => {
    if (type instanceof GraphQLEnumType) {
      const values = type
        .getValues()
        .map((value) => `${docComment(describeField(value), '  ')}  | '${value.name}'`)
        .join('\n')
      return `${docComment([type.description])}export type ${type.name} =\n${values}`
    }
    if (type instanceof GraphQLInputObjectType) {
      const oneOf = type.isOneOf && 'Exactly one field must be given.'
      return (
        `${docComment([type.description, oneOf])}` +
        `export interface ${type.name} {\n${fieldsBlock(Object.values(type.getFields()))}\n}`
      )
    }
    return []
  })

const output = `// Generated by scripts/generate-resolver-types.js from the .gql schema. Do not edit by hand:
// run \`npm run schema:types\` after changing the schema.
import type { GraphQLResolveInfo } from 'graphql'
import type { context } from '../context.js'

export type { GraphQLResolveInfo }

/**
 * The context passed to every resolver, as built by \`app/graphql/context.js\`
 */
export type ResolverContext = Awaited<ReturnType<typeof context>>

${namedTypes.join('\n\n')}

${argsTypes.join('\n\n')}
`

await writeFile(outFile, output)
execFileSync(join(root, 'node_modules/.bin/prettier'), ['--log-level', 'warn', '--write', outFile])
